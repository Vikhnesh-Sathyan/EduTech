
const axios = require("axios");
const FormData = require("form-data");

const pythonClient = axios.create({
    baseURL: process.env.PYTHON_AI_URL,
    timeout: 120000
});

// ==========================================
// INTERNAL AUTHENTICATION
// ==========================================

const getInternalHeaders = () => {

    const secret = process.env.STUDY_COMPANION_INTERNAL_SECRET;

    if (!secret) {
        throw new Error(
            "Study Companion internal secret is not configured."
        );
    }

    return {
        "x-internal-secret": secret
    };
};

// ==========================================
// UPLOAD PDF
// ==========================================

const uploadPdf = async (file, sessionId) => {

    const formData = new FormData();

    formData.append("file", file.buffer, {
        filename: file.originalname,
        contentType: file.mimetype
    });

    // Use the UUID generated by Node.js and saved in MySQL.
    formData.append("session_id", sessionId);

    const response = await pythonClient.post(
        "/study-companion/upload-pdf",
        formData,
        {
            headers: {
                ...formData.getHeaders(),
                ...getInternalHeaders()
            }
        }
    );

    return response.data;
};

