// ==========================================
// UPLOAD TEXT
// ==========================================

const uploadText = async (text, sessionId) => {

    const response = await pythonClient.post(
        "/study-companion/upload-text",
        {
            session_id: sessionId,
            text
        },
        {
            headers: getInternalHeaders()
        }
    );

    return response.data;
};


